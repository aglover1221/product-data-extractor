/**
 * Compile Tailwind globals.css and emit a TS module for inlining in layout.
 * Avoids a render-blocking <link rel="stylesheet"> on first paint (Lighthouse).
 */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const input = path.join(root, "app/globals.css");
const outDir = path.join(root, "app/_generated");
const outCss = path.join(outDir, "styles.css");
const outTs = path.join(outDir, "inline-styles.ts");

fs.mkdirSync(outDir, { recursive: true });

execSync(`npx tailwindcss -i "${input}" -o "${outCss}" --minify`, {
  stdio: "inherit",
  cwd: root
});

const css = fs.readFileSync(outCss, "utf8");
fs.writeFileSync(
  outTs,
  [
    "// Generated by scripts/generate-inline-styles.mjs — do not edit.",
    `export const inlineStyles = ${JSON.stringify(css)};`,
    ""
  ].join("\n")
);

console.log(`Wrote ${path.relative(root, outTs)} (${css.length} bytes)`);
